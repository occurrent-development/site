◊section[#:id "reference-sheets-and-assorted-documents" #:short "Reference sheets"]{Reference Sheets and Assorted Documents}
I have a folder with the following:

◊subsubsection[#:id "normed-growth-charts"]{Normed growth charts.}
Weight, height, head circumference, BMI, waist circumference, height:waist, heart rate, blood pressure. I had to put some of these together from primary sources or UpToDate. All laminated. I use all of them quite frequently.

◊subsubsection[#:id "burt-reading-test"]{BURT reading test.}
This is commonly used in schools and gives a reading age for sight words (but doesn't tell you anything about comprehension). I find ◊link["https://www.childrens-stories.net/reading-age/burt-reading-age-test.pdf"]{this} the most user-friendly version. I use it every couple of weeks.

◊subsubsection[#:id "rey-osterrieth-complex-figure"]{Rey--Osterrieth complex figure.}
Just for gestalt, occasional use.

◊subsubsection[#:id "denver-ii"]{Denver-II.}
Just the summary page. Say what you like about the Denver-II, the visual design of representing all developmental milestones graphically on a single page is spectacular! Edward Tufte eat your heart out! As much as I love the design, I use this much less these days than in the past.

◊subsubsection[#:id "dental-eruption-chart"]{Dental eruption chart.}
Very rarely used, but sometimes a parent points out that a tooth is overdue to erupt and apparently I'm supposed to be able to nod sagely and reassure them. This helps.

