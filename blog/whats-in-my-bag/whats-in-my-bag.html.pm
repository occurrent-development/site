◊section[#:id "other-medical-equipment"]{Other Medical Equipment}
◊subsubsection[#:id "stethoscope"]{Stethoscope.}
I used to carry several of these, including an adult stethoscope for large patients and a differential stethoscope that I made myself. I've now consolidated down to my trusty old Littmann Classic II Pediatric [sic] stethoscope. I think it's excellent.

◊em{Use: Many times daily.◊br{}
Verdict: Excellent.◊br{}
Cost: ~$180.}

◊subsubsection[#:id "sphygmomanometer"]{Sphygmomanometer.}
I use an Erka sphygmomanometer and I love it. It comes with 4 different cuff sizes (although I never use the smallest one). It is ◊em{far} superior to the Welch Allyn: feels great in the hand, much better control of the valve, built to last. No little plastic parts that'll break, no tiny silastic o-rings. For something you will use 10 times a day, do yourself a favour: get the Erka.◊aside{Unfortunately these are currently difficult to find in Australia, with few medical shops stocking them.}

◊em{Use: Many times daily.◊br{}
Verdict: Outstanding◊br{}
Cost: ~$300, but now hard to find.}

◊subsubsection[#:id "ophthalmoscope"]{Ophthalmoscope.}
I use a Heine ophthalmoscope that my Dad gave me when I got into medical school. I've had it on me every day since I started as an intern---it's looked in thousands of eyes. With the O-Scope I have no need for a dedicated otoscope, so now I only carry the ophthalmoscope head. I can't tell you how much better the Heine is than the Welch Allyn---no way would a Welch Allyn still be working after all those years of solid use! ◊aside{◊anchor["welch-allyn-complaint"]I do not like Welch Allyn, though it seems that they've done a good job of convincing people that they make quality kit. It seems to me that the company's focus is on compensating for poor examination technique at the expense of solid build quality. They're all made of plastic with small, flimsy, proprietary, mission-critical parts that you will lose or break. Your kids will not inherit a Welch Allyn anything that they will want to use. Heine, on the other hand, make bullet-proof tools. Both are expensive, but Heine is ◊em{far} better.}

I use an ophthalmoscope for the Brückner test◊cite["buckleyRedReflexExamination2008"] and, occasionally, to look at the fundus◊aside{In my opinion the Welch Allyn panophthalmoscope is, for the paediatrician, a gimmick (I own one). Firstly, it's useless for red reflex, so you'll need to have a regular ophthalmoscope anyway. Secondly, if a paediatrician wants to look in the back of the eye it's to exclude raised ◊sc{ICP}. You don't need a wide field of view for that, you need to see the disc and the vessels. The magnification you get with a traditional ophthalmoscope means you're much more able to appreciate the disc and see spontaneous retinal venous pulsations.}. I look at the fundus for even the slightest indication---not because it's indicated, but to maintain the skill. I can usually assess spontaneous retinal venous pulsations from 4 (occasionally 3) years of age. (Years of practice; helps to be an avid enthusiast!) Those pulsations are really useful: their presence makes raised ◊sc{ICP} very unlikely (except if there is co-occurring raised intra-ocular pressure, which is more a point of trivia); the absence of pulsations tells you nothing about the intracranial pressure◊cite["jacksSpontaneousRetinalVenous2003"].

Every room I work in has ended up with a little red dot on the wall somewhere for kids to look at.

◊em{Use: Monthly.◊br{}
Verdict: Excellent---provided you learn how to do it properly.◊br{}
Cost: Usually around $1,500. Go for build quality over feature set.}

◊section[#:id "dermatology-stuff"]{Dermatology Stuff}
◊subsubsection[#:id "dermatoscope"]{Dermatoscope.}
I use a Heine Delta 20 dermatoscope. I don't use it much, but it is good for hunting scabies or head lice◊cite["haliasosDermoscopyPediatricDermatologist2013b" #:note "For those considering a dermatoscope this, and its two companion pieces, is a fantastic paper."]. I'd replace it with a Dino-Lite for that in a heartbeat. But note that I really have this because I'm an enthusiast; I can't recommend most paediatricians carry a dermatoscope.

◊em{Use: Every month or so.◊br{}
Verdict: Not worth the cost for most paediatricians.◊br{}
Cost: ~$1,500--$2,000.}

