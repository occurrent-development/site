◊section[#:id "maths-kit"]{Maths Kit}
This is just a little bag of tricks for trying to establish a child's numeracy understanding.

◊subsubsection[#:id "wooden-tens-set"]{Wooden tens set.}
I use this frequently. Usually when I am trying to get an idea of a kid's fundamental numeracy skills I start with some problems on a sheet of paper, but if they find that too hard then it is helpful to pull these out to see whether they actually get the concept of units, tens, hundreds. Easy to do some basic arithmetic with these. And stacking the little blocks takes serious fine motor skill!

◊em{Use: A couple of times per week.◊br{}
Verdict: These are great! Strongly recommend.◊br{}
Cost: ~$100 at Office Works.}

◊subsubsection[#:id "tangram-puzzle"]{Tangram puzzle.}
I love giving this to kids. It isn't standardised, but sometimes you just get a really valuable insight into how they approach puzzles. More for gestalt.

◊em{Use: A few times a month.◊br{}
Verdict: I like it, but it's just for gestalt. You could use something else.◊br{}
Cost: $10 from Office Works.}

◊subsubsection[#:id "play-money"]{Play money.}
Some kids have learnt mathematical operations rote, but you suspect that they actually have no idea what is really going on. I make them the shopkeeper, give them some of the wooden blocks ("chocolates", $5 each) and try to buy them. Sometimes this can be very revealing!

◊em{Use: A few times per month.◊br{}
Verdict: I quite like having this.◊br{}
Cost: $8.50 at Office Works.}

◊subsubsection[#:id "wooden-pencils"]{Wooden pencils.}
I write maths problems of varying difficulty, they use pencil and paper to solve them.

