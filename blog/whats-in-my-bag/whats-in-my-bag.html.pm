◊section[#:id "ent-kit"]{ENT kit}
In addition to the O-Scope, I carry:

◊subsubsection[#:id "tongue-depressors"]{Tongue depressors.}
I ◊em{hate} wooden tongue depressors. I still carry some, but I have largely replaced them with Lack tongue depressors, which are infinitely better. They are smooth, so can easily be run over mucosal surfaces; retracting the cheeks to better inspect the buccal/labial vestibule is easy. Leverage is better, so I don’t need to put the blade as far in to get sufficient downward displacement of the tongue. And I cut down fewer trees.

◊em{Use: Most clinics.◊br{}
Verdict: Lack depressors: excellent.◊br{}
Cost: ~$70, but last forever.}

◊subsubsection[#:id "thudicum-nasal-specula"]{Thudicum nasal specula (3, reusable).}
I look in noses often, but need a speculum for the task very rarely. They do the job well, but I could do without them.

◊em{Use: 1--2 times per year.◊br{}
Verdict: Not worth carrying.◊br{}
Cost: ~$40, but last forever.}

◊subsubsection[#:id "st-clair-thomson-mirrors"]{St Clair Thomson mirrors (2, reusable).}
These are like long dental mirrors with two bends; they are for indirect retrograde rhinoscopy (looking up into the nasopharynx). They don't get much use as many kids don't tolerate it (or have a shallow oropharynx that doesn't allow passage of a mirror). I like having them and it is a nice skill to have, but I can't recommend getting them.

◊em{Use: 1--2 times per year.◊br{}
Verdict: Definitely not worth carrying.◊br{}
Cost: ~$80, but last forever.}

◊subsubsection[#:id "alligator-forceps"]{Alligator forceps (2, small, reusable).}
If you're trying to extract a foreign body from the ear (especially if it's smooth and hard) then more often than not these will make the problem worse. But it is common to find "sheets" of dried wax / skin that occlude the drum while remaining tightly adherent to the skin of the canal at one end. Alligator forceps are perfect for grabbing these and pulling them out.

◊em{Use: 1--2 per month.◊br{}
Verdict: Worth it with the O-Scope.◊br{}
Cost: Hugely variable. Aim for under $100 as for external use only.}

◊subsubsection[#:id "teaching-mirror"]{Teaching mirror.}
VorOtek sells these. Just a half-mirror that sticks onto the O-Scope so someone else can see what you can see. I don't currently have any teaching opportunities and I've never actually used it. But maybe one day!

◊em{Use: Haven't yet.◊br{}
Verdict: TBA.◊br{}
Cost: $180.}

