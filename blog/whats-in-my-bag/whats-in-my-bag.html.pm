I always thought these were silly, but now I know that they are excellent when assessing smooth pursuit---it just gives a very precise tracking target.

◊em{Use: A couple of times per year.◊br{}
Verdict: I like it but I can't honestly recommend you get one.◊br{}
Cost: $30.}

◊subsubsection[#:id "snellen-chart"]{Snellen chart (3 metres).}
Worth having, seldom used.

