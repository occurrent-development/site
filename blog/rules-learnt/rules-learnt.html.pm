◊subsubsection[#:id "decompress-the-stomach"]{24. Decompress the stomach.}
This is for paediatric resuscitation, and it's a good one for trainees to keep in mind. A child being bag ventilated via a mask can quickly develop a significantly inflated stomach, which causes problems with both ventilation and venous return. Dropping an NG tube is an easy thing to do but an easy thing to forget to do.

