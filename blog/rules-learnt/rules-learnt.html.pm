◊subsubsection[#:id "nets-conference-call"]{47. Nothing slows you down faster than a ◊sc{NETS} conference call.}
◊sc{NETS} = Neonatal (and paediatric) Emergency Transport Service. It's often the trainee's job to escalate a sick kid to NETS for either expert input or retrieval to a tertiary centre. Sometimes (at night) there might only be one trainee. Do the urgent things first before you get bogged down on a conference call.

◊subsubsection[#:id "intra-osseous"]{48. Intra-osseous. Just do it!}
If a properly sick kid needs IV access and it's hard, don't be scared of putting in an ◊sc{IO} line. It's only scary the first time you do it, but once you've done it (on a human) it's a no-brainer.

◊subsubsection[#:id "use-a-t-piece"]{49. If bagging a patient for any length of time, use a T-piece.}
This one may be archaic now: modern bag-valve masks can provide PEEP.

◊subsubsection[#:id "dont-burn-bridges"]{50. Don't burn bridges.}

◊subsubsection[#:id "rosc-is-tenuous"]{51. ◊sc{ROSC} is tenuous; keep working hard or you will loose it.}
◊sc{ROSC} = Return of Spontaneous Circulation. If you're doing a resuscitation and you get a pulse back, great! But now the work really starts! That person is still sicker and weaker than they've ever been; things can so easily fall apart.

