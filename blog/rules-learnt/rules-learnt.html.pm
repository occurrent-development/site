◊subsubsection[#:id "plane-of-the-back"]{30. The plane of the back must be at right angles to the plane of the bed.}
This is talking about lumbar punctures: positioning really matters. It is very easy for the child to get rotated along their long axis, which will put the needle off trajectory. You have to be really insistent that the back be at right angles to bed.

