From the Greek ὄν, ὄντος (ṓn, óntos: ◊em{being}) + λόγος (lógos: ◊em{account}). Literally translates as "an account of what ◊em{is}".

We need to distinguish two different forms of the word. "Ontology" usually refers to ◊em{the discipline of ontology}. "◊em{An} ontology" refers to a cognitive artefact, a hierarchy of the kinds of things that exist.

