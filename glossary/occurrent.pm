◊define-meta[term]{occurrent}
◊define-meta[aliases]{occurrents; occurrent entity}
◊define-meta[see-also]{continuant}
◊define-meta[added]{2026-10-09}

An entity that unfolds in time and has temporal parts, such as a process, a
performance or a life, as opposed to a ◊term["continuant"]{continuant}, which
persists whole through time.

◊more{
The distinction comes from the formal ontology of the twentieth century and is
older in substance: a river is an occurrent if what matters is the flowing, a
continuant if what matters is the bed. Much of this site argues that
development is better described in the first way than the second.
}
