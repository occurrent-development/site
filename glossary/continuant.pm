◊define-meta[term]{continuant}
◊define-meta[aliases]{continuants}
◊define-meta[see-also]{occurrent}
◊define-meta[added]{2026-10-09}

An entity that persists through time while being wholly present at each moment
it exists, such as an organism, an organ or a table, as opposed to an
◊term["occurrent"]{occurrent}, which has a different part at each moment.
